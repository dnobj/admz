# Values whose key looks like a credential must NEVER be written to the
# audit log. We log the keys (so an operator can tell that an arg was
# present) but mask the value. Rules live in admz.redact (D-2) — shared
# with the chat display layer and fleet-settings masking — which also
# recurses into lists (the old inline version didn't, so a password
# inside a list of dicts reached the audit log in plaintext).
def _sanitize_tool_args(arguments: Any) -> Any:
    """Return a copy of ``arguments`` safe to record in the audit log."""
    from admz.redact import redact_structure

    if not isinstance(arguments, dict):
        return arguments
    return redact_structure(arguments)


def _validate_tool_args(name: str, arguments: Any) -> Optional[str]:
    """CR-5: validate identifier-shaped args against an allow-list.

    Returns None on success, or an error message string on failure.
    The dispatcher converts the message into an ``{"error":
    "InvalidInput", ...}`` envelope that matches the existing error
    shape (DeviceNotFound / PermissionDenied / BackendError).

    Validates: ``device_id``, ``device_ids`` (list), ``account_id``,
    ``facet_name``, ``facets`` (list), ``ref``, ``ref_a``, ``ref_b``.
    Other arguments pass through unexamined.
    """
    if not isinstance(arguments, dict):
        return None
    from admz.validators import validate_identifier, validate_git_ref

    ident_keys = ("device_id", "account_id", "facet_name")
    list_ident_keys = ("device_ids", "facets")
    ref_keys = ("ref", "ref_a", "ref_b", "commit_sha")

    for k in ident_keys:
        v = arguments.get(k)
        if v is None or v == "":
            continue
        try:
            validate_identifier(v, k)
        except ValueError as e:
            return str(e)

    for k in list_ident_keys:
        v = arguments.get(k)
        if v is None:
            continue
        if not isinstance(v, list):
            return f"{k} must be a list"
        kind = "device_id" if k == "device_ids" else "facet_name"
        for item in v:
            try:
                validate_identifier(item, kind)
            except ValueError as e:
                return str(e)

    for k in ref_keys:
        v = arguments.get(k)
        if v is None or v == "":
            continue
        try:
            validate_git_ref(v)
        except ValueError as e:
            return str(e)

    return None


# Task #41: MCP-side parity with the CR-3 REST gate. The REST routes
# DELETE /api/devices/{id}, POST /api/snapshot/restore, and
# POST /api/plans/{id}/execute require_authenticated_principal — but
# their MCP equivalents (delete_device, restore_device, execute_plan)
# had no such gate. Discovered live during the E2E suite's dogfooding:
# the LLM, given an anonymous-principal chat session, called
# delete_device on a real device and the registry actually dropped
# it. This gate closes that asymmetry.
#
# The check is at the dispatcher level (not per-handler) so the
# allow/deny decision is in one place — easy to audit, easy to extend.
#
# Note: set_fleet_setting against PROTECTED_SETTING_KEYS already
# enforces its own anonymous-block inside the handler, so it isn't
# duplicated here. delete_account is intentionally NOT in this set —
# the REST equivalent isn't in CR-3's destructive list either
# (it's audited but not gated; accounts are re-addable).
# ADR-0034 superseded the flat anonymous refusal: every destructive tool now
# takes the SAME deterministic human/widget approval path as device writes —
#   restore_device  → builds a plan (no device writes by itself)
#   execute_plan    → the plan-level url_* gate (execute_gated_plan) blocks
#                     with a confirm widget; approval runs the plan
#   accept_baseline / delete_device → url_only ACTION sessions
#                     (operations.create_action_session) executed on approval
# The gate mechanism below is retained (empty) in case a future tool is truly
# unsuitable for widget approval; with ADR-0033 (windows-local auth) callers
# are authenticated anyway, so audit rows carry a real identity either way.
_DESTRUCTIVE_MCP_TOOLS = frozenset()


def _annotate_snapshot_summary(summary: Dict[str, Any]) -> Dict[str, Any]:
    """Add an unambiguous ``committed`` flag + human-readable ``message``
    to a SnapshotResult.to_summary() dict.

    The underlying snapshot engine returns ``git_sha: null`` when the
    captured config is identical to the working tree — a legitimate
    "nothing changed" outcome rather than a failure. The LLM was
    interpreting the null SHA as failure and telling users "I
    couldn't retrieve the commit SHA", which was both inaccurate and
    confusing. This wrapper makes the two cases distinguishable:

      * ``committed=true, git_sha=<sha>, message="Snapshot committed..."``
      * ``committed=false, git_sha=null, message="Device configuration
         unchanged since last snapshot — nothing to commit."``
    """
    sha = summary.get("git_sha")
    out = dict(summary)
    if sha:
        out["committed"] = True
        out["message"] = (
            f"Snapshot committed as {sha[:12]}. "
            f"{summary.get('facets_succeeded', 0)} facet(s) captured."
        )
    else:
        out["committed"] = False
        out["message"] = (
            "Device configuration unchanged since the last snapshot — "
            "nothing to commit. This is a successful no-op; the device "
            "was probed and its config matches what's already in the "
            "archive at HEAD."
        )
    return out


def _tool_resource(name: str, arguments: Any) -> str:
    """Build a short ``resource`` string for the audit row.

    Many MCP tools take a ``device_id`` / ``account_id``; surface that
    so the audit log groups by device. For tools without identifiers
    we fall back to the bare tool name.
    """
    if not isinstance(arguments, dict):
        return f"mcp:{name}"
    parts = [f"mcp:{name}"]
    device_id = arguments.get("device_id")
    if device_id:
        parts.append(f"device:{device_id}")
    account_id = arguments.get("account_id")
    if account_id:
        parts.append(f"account:{account_id}")
    # Surface the specific operation so "who factory-defaulted device X" /
    # "who rebooted Y" is searchable in the resource string, not just details.
    operation_id = arguments.get("operation_id")
    if operation_id:
        parts.append(f"op:{operation_id}")
    # ADR-0053: the fleet-settings tools take the key as `key`, and without it
    # the audit row could not answer "who changed config_ignore_patterns?" —
    # the key lived only inside details.args, which is not what an auditor
    # queries. The web rows have always encoded it (`confirm_settings:levels`).
    # Scoped to the settings tools on purpose: `key` is a generic argument
    # name and other tools use it for unrelated things.
    if name in ("set_fleet_setting", "get_fleet_settings"):
        setting_key = arguments.get("key")
        if setting_key:
            parts.append(f"setting:{setting_key}")
    return "/".join(parts)


