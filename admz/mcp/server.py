    async def _create_action_rule(
        self, device_id: str, condition_id: str, action_token: str,
        param_choices: Optional[Dict[str, Any]] = None,
        rule_name: Optional[str] = None,
        demo: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Gate creating a device event rule (ADR-0034 widget-gated action).

        Validates the spec via the atlas (fail fast in chat on an unbuildable
        rule), then returns the approval card. The rule is only created after
        the user approves — the executor re-renders and runs the SOAP sequence,
        so no rendered body (or secret) is ever stored in the confirm session.

        ``demo`` (name-or-id, ADR-0050 Phase B): correlate the rule with a demo —
        on approval its membership is recorded and its condition topic becomes the
        demo's signal. Resolved here so an unknown demo fails fast in chat."""
        if not self.registry.device_exists(device_id):
            raise DeviceNotFoundError(f"Device not found: {device_id}")
        from admz import operations
        from admz.rules import capabilities
        info = self.registry.get_device_info(device_id)
        model = info.get("model") or ""
        rule_name = rule_name or "AtlasRule"
        param_choices = dict(param_choices or {})

        demo_id = demo_name = None
        if demo:
            from admz.demos.actions import DemoActionError
            try:
                demo_obj = self._resolve_demo(demo)
                demo_id, demo_name = demo_obj.id, demo_obj.name
            except DemoActionError as exc:
                return {"success": False, "error": str(exc)}

        result = capabilities.build(
            model, condition_id, action_token,
            param_choices=param_choices, rule_name=rule_name)
        if not getattr(result, "available", False):
            return {"success": False,
                    "error": getattr(result, "error", None)
                    or "This rule cannot be built for this device."}

        action = capabilities.action_for(model, action_token)
        condition = capabilities.condition_for(model, condition_id)

        # #194 — FAIL CLOSED on a secret supplied through chat. `param_choices`
        # is persisted verbatim into `confirm_sessions.action_json`
        # (operations.py: json.dumps of the payload, no redaction), and a
        # *completed* session is never cleaned up (#266), so anything landing
        # here stays on disk indefinitely, in the same SQLite file as the device
        # registry. Rejecting rather than stripping is deliberate: the previous
        # `param_choices.pop(...)` dropped the key silently, which is
        # indistinguishable to the caller from a key that was never sent — so a
        # leak that slipped past the (too-narrow) match looked exactly like a
        # success. Redacting the payload on the way into the store was measured
        # and REJECTED: `redact_structure` masks `secret_fields` too, and
        # `rule_capture.py` reads that back to render the capture form, so it
        # would break the very mechanism this protects.
        offending = capabilities.secret_choice_keys(action, param_choices) if action else []
        if offending:
            return {
                "success": False,
                "error": (
                    f"Refusing to accept {', '.join(sorted(offending))} in param_choices: "
                    "this is a credential and it would be written to the pending-approval "
                    "record in cleartext. Recipient login/password are collected from the "
                    "user on a secure form instead — omit them and call again, and you will "
                    "be given a capture link. Secondary credentials (proxy_*, pop_*) have no "
                    "capture form in this version and cannot be supplied by any route: tell "
                    "the user this rule cannot set them here."
                ),
                "rejected_params": sorted(offending),
            }

        # ADR-0050 Phase B: the condition's ONVIF topic (the device publishes it
        # independently of the rule → it IS the demo's correlated signal). Carried
        # in the action payload so the executor records it on approval.
        demo_extra: Dict[str, Any] = {}
        if demo_id:
            demo_extra = {"demo_id": demo_id, "demo_name": demo_name,
                          "condition_topic": getattr(condition, "topic", None)}

        # Create-time lint: a rule whose condition topic has no publisher on
        # THIS unit saves fine and then never fires. Block conditions that
        # depend on an ACAP the device doesn't run; warn on the known-trap
        # bare ONVIF motion topic when an analytics app is what does motion.
        apps = capabilities.device_applications(
            self.git_repo, self.registry, device_id)
        publisher_error = capabilities.check_condition_publisher(condition, apps)
        if publisher_error:
            return {"success": False, "error": publisher_error,
                    "device_applications": apps}
        caution = capabilities.condition_caution(condition, apps)

        label = info.get("nickname") or model or device_id
        reason = capabilities.describe_rule(
            result, device_label=label, device_id=device_id,
            rule_name=rule_name, condition=condition, action=action)
        if caution:
            reason = f"{reason} WARNING: {caution}"
        if demo_id:
            reason = (f"{reason} This rule is correlated with demo "
                      f"'{demo_name}' — on approval its condition topic becomes "
                      "the demo's signal.")

        # Recipient-credential actions (HTTP/SMTP/send-*): the login/password
        # must be captured out-of-band via a secure form, never taken from chat.
        # Arm the confirm session now, but route the user through the capture
        # form first; the secret is merged in at execution time.
        secret_fields = (
            capabilities.primary_recipient_secret_fields(action) if action else [])
        if secret_fields:
            # No strip here any more: the fail-closed check above already
            # refused every sensitive key, by the same matching rule the atlas
            # resolver uses, so nothing is left to pop (#194).
            session = operations.create_action_session(
                action="create_action_rule", device_id=device_id,
                payload={"device_id": device_id, "model": model,
                         "condition_id": condition_id, "action_token": action_token,
                         "param_choices": param_choices, "rule_name": rule_name,
                         "requires_secret_capture": True,
                         "secret_fields": secret_fields, **demo_extra},
                reason=reason)
            return {
                "success": False,
                "needs_recipient_credentials": True,
                "capture_url": f"/capture/rule/{session.token}",
                "message": (
                    f"The action '{action_token}' delivers to a recipient that "
                    "needs a login and password. To keep the secret out of this "
                    "conversation, the user enters it on a secure form. Give the "
                    f"user this link EXACTLY: /capture/rule/{session.token} — after "
                    "they submit the credentials they'll be shown an approval "
                    "button. Do NOT ask for the password here, and do not invent "
                    "or alter the link."
                ),
            }

        session = operations.create_action_session(
            action="create_action_rule", device_id=device_id,
            payload={"device_id": device_id, "model": model,
                     "condition_id": condition_id, "action_token": action_token,
                     "param_choices": param_choices, "rule_name": rule_name,
                     **demo_extra},
            reason=reason)
        env = operations.blocked_envelope(session)
        env["success"] = False
        if caution:
            env["warnings"] = [caution]
        return env

