    async def _set_fleet_setting(
        self, key: str, value: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Set, delete, or capture a fleet-wide setting.

        **Deny by default (ADR-0053).** Only keys declared in
        ``admz.setting_policy.LLM_WRITABLE_SETTING_KEYS`` are writable from
        here; every other key is refused whether or not anyone remembered to
        list it. This method is the *one* production enforcement point of that
        rule — there is no generic REST fleet-settings write route — which is
        why the gate below is the first thing that happens.
        """
        # The gate. Must go through is_protected_setting() rather than testing
        # membership of any set: the predicate carries both the allow-set rule
        # and the confirm_level_* namespace rule. This call site is the reason
        # that matters — it once tested `key in PROTECTED_SETTING_KEYS`
        # directly, so the GH #152 fix would have been a no-op here had it been
        # applied only to the predicate.
        if is_protected_setting(key):
            return {
                "success": False,
                "error": (
                    f"Setting '{key}' is protected and cannot be changed from "
                    f"chat. An operator "
                    f"can set it with `python -m admz settings set {key} "
                    f"<value>`, or from the web UI (/confirm-settings for "
                    f"confirmation levels)."
                ),
            }

        # Past the gate the key is allow-listed. A capture-only key still never
        # takes its value from the model: FR-MCP-008 and
        # user-stories/device-onboarding.md:84 both require the password to
        # arrive through the out-of-band capture URL and "never typed into the
        # LLM chat". The code accepted a supplied value anyway; it no longer
        # does.
        #
        # This refusal does NOT keep the password out of the audit row — an
        # earlier version of this comment claimed it did, and that was wrong
        # (#217). ``args_sanitized`` is computed from the raw arguments before
        # dispatch, and all three audit sites record it whatever the handler
        # decides, so a refused call still carried the plaintext. What masks it
        # is the sibling rule in ``admz.redact.sibling_masked_fields``; this
        # gate only stops the value being *stored*.
        if is_capture_only(key):
            if value is not None:
                return {
                    "success": False,
                    "error": (
                        f"Setting '{key}' cannot be given a value from chat. "
                        "Call set_fleet_setting again with the 'value' "
                        "argument omitted to get a one-time capture URL for "
                        "the user to type the password into — it never enters "
                        "the conversation."
                    ),
                }
            base_url = os.getenv("ADMZ_BASE_URL", "http://localhost:4242")
            session = capture_store.create_fleet_session(
                setting_key=key,
                label="Fleet default password for device provisioning",
            )
            url = f"{base_url}/capture/fleet/{session.token}"
            return {
                "success": True,
                "action": "capture",
                "key": key,
                "capture_url": url,
                "token": session.token,
                "expires_in_seconds": int(session.ttl),
                "message": (
                    "Open the URL to enter the password securely. "
                    "The password never appears in the chat."
                ),
            }

        if value is None:
            return {
                "success": False,
                "error": "Value is required for non-password settings.",
            }

        if not value:
            deleted = fleet_settings.delete(key)
            return {
                "success": True,
                "action": "deleted" if deleted else "not_found",
                "key": key,
            }

        fleet_settings.set(key, value)
        # #158: this line was its own hand-rolled "password" in key.lower()
        # test — a fourth instance of the same drift admz/redact.py exists to
        # stop (D-2). Currently only default_username can ever reach here
        # with a real value (default_password is capture-only and returns
        # above; everything else is refused by is_protected_setting before
        # this point) so nothing sensitive echoes back today — but that was
        # true only because of the allow-list, not because this predicate
        # was correct, and the allow-list is exactly the kind of thing that
        # grows. Use the canonical predicate/formatter so it can't drift
        # again if it ever does.
        from admz.fleet_settings import is_sensitive_setting_key, mask_setting_value

        display_value = (
            mask_setting_value(value) if is_sensitive_setting_key(key) else value
        )
        return {
            "success": True,
            "action": "set",
            "key": key,
            "value": display_value,
        }

