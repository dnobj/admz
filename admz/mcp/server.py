def _warn_base_url_mismatch() -> None:
    """If ADMZ is deployed behind a reverse proxy with Windows IWA,
    ADMZ_BASE_URL must point at the public-facing URL (e.g.
    ``https://admz.company.com``), not the localhost uvicorn URL.
    Otherwise capture / confirm URLs handed to users will bypass auth
    or fail to reach the proxy at all.

    This is a soft warning, not a hard error — local dev installs
    correctly use the localhost default.
    """
    backend = (os.getenv("ADMZ_AUTH_BACKEND", "none") or "none").lower()
    if backend not in ("windows", "composite"):
        return
    base_url = os.getenv("ADMZ_BASE_URL", "http://localhost:4242")
    if "localhost" in base_url or "127.0.0.1" in base_url:
        logger.warning(
            "ADMZ_AUTH_BACKEND=%s with ADMZ_BASE_URL=%r — capture/confirm "
            "URLs generated by MCP will point at localhost and bypass the "
            "reverse proxy. Set ADMZ_BASE_URL to the IIS-facing URL "
            "(e.g. https://admz.example.com).",
            backend, base_url,
        )


_warn_base_url_mismatch()


