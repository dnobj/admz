    async def _execute_operation(
        self,
        device_id: str,
        operation_id: str,
        params: Dict[str, str],
        family: str,
    ) -> Dict[str, Any]:
        """Execute a single catalog operation.

        Honors the per-risk-level confirmation policy
        (ADR-0006). Operations whose effective confirmation level
        is ``none`` run inline; everything else returns a blocked
        response with a confirm_token. The token is consumed via
        ``confirm_dangerous_operation`` (still named that for
        backward compat, but now handles every risk level) or via
        the web ``/confirm/{token}`` form.

        Defaults (overridable per-fleet via
        ``confirm_level_<risk>`` settings):
          - read-only         → none      (just run)
          - normal            → none      (just run)
          - service-affecting → url_only          (deterministic widget)
          - dangerous         → url_and_password  (widget + password)
        """
        from admz import operations

        try:
            return await operations.execute_gated_operation(
                device_id=device_id,
                operation_id=operation_id,
                family=family,
                params=params or {},
                catalog=self.catalog,
                # executors are only used on the execute path; the gate also
                # reads the registry to warn when the device has no stored
                # credentials (the approval would just fail with 401).
                registry=getattr(self, "registry", None),
                executors=getattr(self, "executors", None),
            )
        except operations.OperationNotFoundError:
            # Active guidance (MCP/LLM-specific): when the LLM passes a made-up
            # operation_id, nudge it to discover the right one via query_catalog
            # rather than guessing another. (The REST surface returns a plain
            # 404 — different audience.) We've seen Gemini repeatedly invent
            # ids like 'system.cgi:restart' that don't exist; this message is
            # the only thing in the trace that can correct it.
            return {
                "success": False,
                "error": (
                    f"Operation '{operation_id}' not found in the {family} "
                    f"catalog. DO NOT guess another operation_id. Call "
                    f"query_catalog(device_id='{device_id}', intent='<what "
                    f"you want to do, e.g. restart or reboot>') to discover "
                    f"the correct operation_id, then retry execute_operation "
                    f"with the id from the result."
                ),
                "operation_id_attempted": operation_id,
                "next_step": "query_catalog",
            }
        except operations.NoExecutorError:
            return {
                "success": False,
                "error": f"No executor available for API family '{family}'",
            }

    async def _confirm_dangerous(self, confirm_token: str) -> Dict[str, Any]:
        """Confirm and execute a blocked operation (any risk class).

        The token is looked up in the shared SQLite ConfirmStore — a token
        issued by either MCP or the REST surface can be confirmed by either.

        Refuses tokens whose configured confirmation_level requires a URL
        flow (url_only / url_and_password). Those can only be approved
        via the web /confirm/{token} page, since MCP has no way to
        prompt the user for a password (``enforce_url_flow_block=True``).
        """
        from admz import operations

        return await operations.consume_confirmation(
            confirm_token,
            catalog=self.catalog,
            registry=self.registry,
            executors=self.executors,
            confirmed_by="mcp",
            enforce_url_flow_block=True,
        )

