    # --- Audit-log search (who-did-what) ---------------------------------

    @staticmethod
    def _parse_audit_ts(v: Any) -> Optional[float]:
        """ISO-8601 or unix → unix float; None if unparseable."""
        if v is None:
            return None
        if isinstance(v, (int, float)):
            return float(v)
        s = str(v).strip()
        try:
            return float(s)
        except ValueError:
            pass
        try:
            from datetime import datetime
            return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()
        except ValueError:
            return None

    @staticmethod
    def _parse_audit_window(s: Any) -> Optional[float]:
        """'30m' / '2h' / '7d' / '1w' → seconds; None if unparseable."""
        if not s:
            return None
        import re
        m = re.match(r"^\s*(\d+(?:\.\d+)?)\s*([a-zA-Z]+)\s*$", str(s))
        if not m:
            return None
        n, unit = float(m.group(1)), m.group(2).lower()
        units = {"s": 1, "sec": 1, "m": 60, "min": 60, "h": 3600, "hr": 3600,
                 "hour": 3600, "d": 86400, "day": 86400, "w": 604800, "week": 604800}
        for k in sorted(units, key=len, reverse=True):
            if unit.startswith(k):
                return n * units[k]
        return None

    def _fmt_audit_entry(self, e: Any) -> Dict[str, Any]:
        from datetime import datetime, timezone
        d = e.details or {}
        args = d.get("args") if isinstance(d.get("args"), dict) else {}
        bits = []
        op = args.get("operation_id") or d.get("operation_id")
        if op:
            bits.append(f"op={op}")
        if d.get("confirmed_by"):
            bits.append(f"approved_by={d['confirmed_by']}")
        if d.get("risk_level"):
            bits.append(f"risk={d['risk_level']}")
        if d.get("intent"):
            bits.append(f"intent={d['intent']}")
        # Identifiers captured off the execution outcome (e.g. the rule id a
        # confirm.approve row actually created). Driven off the same allow-list
        # the writer uses, so adding a key there surfaces it here rather than
        # being silently dropped by this whitelist.
        from admz.audit import OUTCOME_IDENTITY_KEYS
        for key in OUTCOME_IDENTITY_KEYS:
            if d.get(key):
                bits.append(f"{key}={d[key]}")
        if d.get("summary"):
            bits.append(str(d["summary"]))
        return {
            "time": datetime.fromtimestamp(e.timestamp, timezone.utc).isoformat(),
            "actor": e.requester,
            "auth_source": e.auth_source,
            "action": e.action,
            "resource": e.resource,
            "success": e.success,
            # Curated summary only — never the raw args (already sanitized, but
            # keep the surface tight).
            "summary": "; ".join(bits) if bits else None,
            "error": e.error_message or None,
        }

    def _search_audit_log(self, arguments: Dict[str, Any]) -> Dict[str, Any]:
        import time as _time
        from datetime import datetime, timezone

        from admz.audit import AuditLog

        start = self._parse_audit_ts(arguments.get("since"))
        end = self._parse_audit_ts(arguments.get("before"))
        win = self._parse_audit_window(arguments.get("within"))
        if win and start is None:
            start = _time.time() - win

        entries = AuditLog().search(
            start=start, end=end,
            requester=arguments.get("actor"),
            action=arguments.get("action"),
            device=arguments.get("device_id"),
            text=arguments.get("query"),
            success=arguments.get("success"),
            limit=int(arguments.get("limit") or 30),
        )
        window = None
        if start or end:
            window = {
                "since": datetime.fromtimestamp(start, timezone.utc).isoformat() if start else None,
                "before": datetime.fromtimestamp(end, timezone.utc).isoformat() if end else None,
            }
        return {
            "success": True,
            "count": len(entries),
            "window": window,
            "entries": [self._fmt_audit_entry(e) for e in entries],
        }

    def _list_tasks(self, arguments: Dict[str, Any]) -> Dict[str, Any]:
        """Unified view of schedule + detection tasks (ADR-0037)."""
        from admz.tasks.store import tasks_store

        device_id = arguments.get("device_id")
        kind = arguments.get("kind")
        tasks = tasks_store.list(trigger_kind=kind, device_id=device_id)
        out = []
        for t in tasks:
            d = t.to_dict()
            if t.trigger_kind == "schedule":
                d["when"] = f"every {t.interval_human}"
            else:
                d["when"] = f"when {t.event}"
            out.append(d)
        return {"success": True, "count": len(out), "tasks": out}

    def _search_activity(self, arguments: Dict[str, Any]) -> Dict[str, Any]:
        """Search the live device-event store (ADR-0041). Read-only."""
        import time as _time

        from admz.events.store import EventStore

        win = self._parse_audit_window(arguments.get("within"))
        since_ms = int((_time.time() - win) * 1000) if win else None
        limit = max(1, min(int(arguments.get("limit") or 50), 500))
        events = EventStore().query(
            source="device",
            type_filter=arguments.get("type"),
            device_id=arguments.get("device_id"),
            device_filter=arguments.get("device"),
            since_ms=since_ms,
            limit=limit,
        )
        # Trim each event to the fields an agent reasons over (drop the raw
        # nested data envelope; the summary + category carry the signal).
        out = []
        for e in events:
            data = e.get("data") or {}
            out.append({
                "ts": e.get("ts"),
                "device_id": e.get("device_id"),
                "device_name": e.get("device_name"),
                "type": e.get("type"),
                "category": data.get("category"),
                "summary": e.get("summary"),
            })
        return {"success": True, "count": len(out), "events": out}

    def _get_advanced_capabilities(self) -> Dict[str, Any]:
        """The advanced-capability inventory (GH #132, ADR-0052). Read-only.

        Returns ``capabilities.snapshot()`` verbatim — the same payload
        ``GET /api/capabilities`` serves, so an agent diagnosing an install in
        chat and an operator reading the JSON are looking at one shape.

        There is deliberately no ``set_advanced_capability`` counterpart, and
        adding one later would be a mistake, not an omission being corrected:
        these switches change how the model's own gates behave, so a write tool
        would put the LLM one call away from enabling its own approver. See the
        module docstring of ``admz/mcp/tools/capabilities.py``. The registry's
        setting keys are refused by the generic ``set_fleet_setting`` tool too
        — the refusal is enforced twice on purpose. Since ADR-0053 that second
        refusal needs no per-key upkeep: everything outside the two-key
        allow-set is denied, so a capability added tomorrow is covered without
        anyone remembering to list it.
        """
        from admz import capabilities as _capabilities

        return {"success": True, **_capabilities.snapshot()}

    async def _provision_device(
        self, arguments: Dict[str, Any]
    ) -> Dict[str, Any]:
        device_id = arguments.get("device_id")
        host = arguments.get("host")
        username = arguments.get("username", "root")
        user_password = arguments.get("password")
        force_change = arguments.get("force_change", False)

        if not host and not device_id:
            return {
                "success": False,
                "error": "Either 'host' or 'device_id' must be provided",
            }

        if device_id and not host:
            if not self.registry.device_exists(device_id):
                raise DeviceNotFoundError(f"Device not found: {device_id}")
            device_info = self.registry.get_device_info(device_id)
            host = device_info.get("host") or device_info.get("ip_address")
            if not host:
                return {
                    "success": False,
                    "error": f"Device '{device_id}' has no host/IP address",
                }

        probe = await probe_credentials(host)

        if probe.status == ProbeStatus.UNREACHABLE:
            return {
                "success": False,
                "status": "unreachable",
                "host": host,
                "detail": probe.detail,
            }

        auto_registered = False
        if not device_id:
            serial = (probe.device_info or {}).get("serial_number")
            if serial and len(serial.replace(":", "").replace("-", "")) == 12:
                device_id = self._serial_to_mac(serial)
            else:
                return {
                    "success": False,
                    "error": (
                        "Could not determine device serial/MAC from probe. "
                        "Register the device manually and use device_id instead."
                    ),
                    "host": host,
                    "device_info": probe.device_info,
                }

            if not self.registry.device_exists(device_id):
                reg_info = {
                    "host": host,
                    "ip_address": host,
                    "mac_address": device_id,
                    "serial_number": serial,
                    "model": (probe.device_info or {}).get("model", ""),
                    "firmware_version": (probe.device_info or {}).get(
                        "firmware_version", ""
                    ),
                    "nickname": (probe.device_info or {}).get(
                        "friendly_name", ""
                    ),
                    "manufacturer": "Axis Communications",
                    "tags": ["axis", "auto-registered"],
                }
                self.registry.add_device(device_id, reg_info)
                auto_registered = True

        password_source = "provided"
        if user_password:
            new_password = user_password
        else:
            fleet_default = fleet_settings.get("default_password")
            if fleet_default:
                new_password = fleet_default
                password_source = "fleet_default"
            else:
                new_password = self._generate_device_password()
                password_source = "generated"

        if probe.status == ProbeStatus.FACTORY_DEFAULT:
            ok, error = await self._execute_on_host(
                host, "pwdgrp.cgi:add-user",
                params={
                    "username": username,
                    "password": new_password,
                    "group": "root",
                    "secondary_groups": "admin:operator:viewer:ptz",
                },
                auth_method="none",
            )
            if not ok:
                return {
                    "success": False,
                    "status": "vapix_error",
                    "device_id": device_id,
                    "action_taken": "create_user_failed",
                    "error": error,
                }

            self._store_provisioned_creds(device_id, username, new_password)
            # Device now requires auth — store per-protocol info from probe
            auth_updates: Dict[str, Any] = {"auth_method": "digest"}
            if probe.auth:
                auth_updates["auth"] = probe.auth
            self.registry.update_device_info(device_id, auth_updates)

            return {
                "success": True,
                "status": "provisioned",
                "action_taken": "created_user",
                "device_id": device_id,
                "host": host,
                "username": username,
                "password_source": password_source,
                "auto_registered": auto_registered,
                "detail": (
                    f"Created admin user '{username}' on factory-default "
                    f"device. Credentials stored. The password stays in "
                    f"ADMZ; for human login mint a temporary account with "
                    f"create_temp_credentials."
                ),
            }

        if probe.status == ProbeStatus.AUTHENTICATED:
            # Store detected auth info from probe
            auth_updates_auth: Dict[str, Any] = {}
            if probe.auth_method:
                auth_updates_auth["auth_method"] = probe.auth_method
            if probe.auth:
                auth_updates_auth["auth"] = probe.auth
            if auth_updates_auth:
                self.registry.update_device_info(
                    device_id, auth_updates_auth
                )

            if not force_change:
                self._store_provisioned_creds(
                    device_id, probe.username, probe.password
                )
                return {
                    "success": True,
                    "status": "already_configured",
                    "action_taken": "stored_existing_credentials",
                    "device_id": device_id,
                    "host": host,
                    "username": probe.username,
                    "auto_registered": auto_registered,
                    "detail": (
                        f"Device authenticated with legacy defaults as "
                        f"'{probe.username}'. Credentials stored. Consider "
                        f"using force_change=true to rotate the password."
                    ),
                }

            ok, error = await self._execute_on_host(
                host, "pwdgrp.cgi:update-user",
                params={
                    "username": username,
                    "password": new_password,
                },
                credentials={
                    "username": probe.username,
                    "password": probe.password,
                },
                auth_method=probe.auth_method or "digest",
                auth=probe.auth,
            )
            if not ok:
                self._store_provisioned_creds(
                    device_id, probe.username, probe.password
                )
                return {
                    "success": False,
                    "status": "vapix_error",
                    "device_id": device_id,
                    "action_taken": "password_change_failed",
                    "error": error,
                    "detail": (
                        "Password change failed, but old credentials "
                        "were stored successfully."
                    ),
                }

            self._store_provisioned_creds(device_id, username, new_password)

            return {
                "success": True,
                "status": "provisioned",
                "action_taken": "changed_password",
                "device_id": device_id,
                "host": host,
                "username": username,
                "password_source": password_source,
                "auto_registered": auto_registered,
                "detail": (
                    f"Changed password for '{username}'. New credentials "
                    f"stored. The password stays in ADMZ; for human login "
                    f"mint a temporary account with create_temp_credentials."
                ),
            }

        if probe.status == ProbeStatus.AUTH_FAILED:
            if probe.auth_method:
                self.registry.update_device_info(
                    device_id, {"auth_method": probe.auth_method}
                )
            return {
                "success": False,
                "status": "auth_failed",
                "device_id": device_id,
                "host": host,
                "auto_registered": auto_registered,
                "detail": (
                    "Cannot authenticate with any known credentials. "
                    "Use capture_credentials to provide the password "
                    "manually, or use test_device_credentials with "
                    "specific passwords to probe further."
                ),
            }

        return {
            "success": False,
            "status": probe.status.value,
            "device_id": device_id,
            "detail": probe.detail,
        }

