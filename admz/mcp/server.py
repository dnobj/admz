class ADMZMCPServer:
    """
    MCP server for ADMZ device management.

    Provides tools for LLMs to interact with device registry including:
    - Device discovery and search
    - Credential retrieval
    - Device registration and management
    - Account management
    """

    def __init__(
        self,
        registry: Optional[DeviceRegistry] = None,
        catalog_path: Optional[str] = None,
    ):
        """
        Initialize ADMZ MCP server.

        Args:
            registry: Device registry instance. If None, will create from environment.
            catalog_path: Path to the operations catalog directory.
                If None, uses ADMZ_CATALOG_PATH env var or ./catalog.
        """
        self.server = Server("admz")
        # name -> advertised inputSchema, for the argument validation that mcp
        # 1.x did inside its @server.call_tool() decorator. Populated lazily and
        # refreshed on a miss; see `_tool_schema` in _register_handlers.
        self._tool_schemas: Dict[str, Any] = {}
        self.registry = registry or create_device_registry()

        # Shared component stack — same builder the FastAPI AppContext uses.
        # Running MCP + the FastAPI app in one process previously created
        # two SnapshotScheduler instances writing to the same schedules.json;
        # going through build_components is the single source of truth.
        from admz.components import build_components

        components = build_components(
            self.registry,
            catalog_path=catalog_path,
        )
        self.catalog = components.catalog
        self.resolver = components.resolver
        self.executors = components.executors
        # ADR-0039/0040: discovered platform modules (devices, acs_pro). Drives
        # the module tool surface below; a module self-gates its tools (ACS Pro
        # returns none until connected).
        self.module_registry = components.module_registry
        self.plan_engine = components.plan_engine
        self.git_repo = components.git_repo
        self.snapshot_engine = components.snapshot_engine
        self.restore_builder = components.restore_builder
        self.drift_detector = components.drift_detector
        self.scheduler = components.scheduler
        # The whole bundle, for shared cores that take a ctx-shaped object
        # (demo actions use .demo_store/.registry/.git_repo/.drift_detector/
        # .plan_engine/... — Components is duck-compatible with AppContext).
        self.components = components

        # MCP-only: knowledge base (product hints) and capabilities
        # (per-model API support). These are not currently exposed via
        # the REST API, so they're not part of the shared Components.
        catalog_path_resolved = str(components.catalog.catalog_path)
        self.knowledge_loader = KnowledgeLoader(catalog_path_resolved)
        self.knowledge_resolver = KnowledgeResolver(self.knowledge_loader)
        self.capabilities_loader = CapabilitiesLoader(catalog_path_resolved)
        self.capabilities_resolver = CapabilitiesResolver(self.capabilities_loader)

        # Note: confirmation tokens live in the shared SQLite ConfirmStore
        # (admz/api/confirm_store.py) so they're cross-process and shared
        # with the REST surface. There used to be a separate in-memory
        # _confirm_tokens dict here — see Phase 2E in
        # docs/specification/review-followup.md.

        # Temporary credential manager
        self.temp_creds = TempCredentialManager()

        # CR-4: reconstruct the calling principal from env vars the
        # MCP pool sets when it spawns this subprocess. When the MCP
        # server runs standalone (e.g. `python -m admz mcp` for an
        # external client) the env vars aren't set and we fall back
        # to a synthetic "mcp-standalone" identity that audit-log
        # rows attribute to ``mcp-standalone``. Either way, every
        # call_tool dispatch can produce an audit row with a
        # meaningful requester.
        self.principal = self._build_principal_from_env()

        # Register tool handlers
        self._register_handlers()

    @staticmethod
    def _build_principal_from_env():
        """Read ADMZ_PRINCIPAL_* env vars into a :class:`Principal`.

        Returns a fresh Principal regardless of input shape — when
        no env vars are set, we return a synthetic ``mcp-standalone``
        principal so audit rows are still meaningful. The shape
        matches what :func:`admz.chatbot.mcp_pool._principal_to_env`
        emits on the calling side.
        """
        import os

        from admz.auth import Principal

        name = os.getenv("ADMZ_PRINCIPAL_NAME")
        if not name:
            return Principal(
                name="mcp-standalone",
                display_name="mcp-standalone",
                source="mcp-standalone",
                is_anonymous=False,
            )
        display = os.getenv("ADMZ_PRINCIPAL_DISPLAY_NAME") or name
        domain = os.getenv("ADMZ_PRINCIPAL_DOMAIN") or None
        source = os.getenv("ADMZ_PRINCIPAL_SOURCE") or "none"
        groups_raw = os.getenv("ADMZ_PRINCIPAL_GROUPS") or ""
        groups = [g.strip() for g in groups_raw.split(",") if g.strip()]
        return Principal(
            name=name,
            display_name=display,
            domain=domain,
            groups=groups,
            source=source,
            is_anonymous=(name == "anonymous" or source == "none"),
        )

